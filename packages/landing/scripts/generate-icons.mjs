#!/usr/bin/env node
/**
 * Regenerates `src/components/icon-paths.ts` from the lucide icon data the app
 * already depends on (`lucide-react` in packages/frontend). Inlining the paths
 * keeps the landing free of icon-package code while matching the app's icons
 * pixel for pixel.
 *
 * Usage: bun run icons:generate   (from packages/landing)
 */
import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const landingDir = join(here, "..");

const ICONS = [
  "sparkles",
  "arrow-right",
  "mail-check",
  "cpu",
  "bar-chart-3",
  "mail",
  "globe-2",
  "file-text",
  "repeat",
  "shield-check",
  "plus",
  "calendar-clock",
  "chevron-down",
];

// Some lucide names are aliases that re-export another icon file.
const ALIASES = {
  "bar-chart-3": "chart-column",
  "globe-2": "earth",
};

const require = createRequire(join(landingDir, "..", "frontend", "package.json"));
const lucideDir = dirname(require.resolve("lucide-react/package.json"));
const iconsDir = join(lucideDir, "dist/esm/icons");

const kebab = value => value.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`);

function renderNode([tag, attrs]) {
  const rendered = Object.entries(attrs)
    .filter(([key]) => key !== "key")
    .map(([key, value]) => `${kebab(key)}="${value}"`)
    .join(" ");
  return `<${tag} ${rendered} />`;
}

const entries = [];
for (const icon of ICONS) {
  const file = ALIASES[icon] ?? icon;
  const mod = await import(pathToFileURL(join(iconsDir, `${file}.mjs`)).href);
  entries.push([icon, mod.__iconData.node.map(renderNode).join("")]);
}

const body = entries
  .map(([name, markup]) => `  ${JSON.stringify(name)}: ${JSON.stringify(markup)},`)
  .join("\n");

const file = `// Generated by \`bun run icons:generate\` from lucide-react node data.
// Only the icons the landing uses are inlined here so the page ships zero
// icon-package code.
export const ICON_PATHS = {
${body}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`;

await writeFile(join(landingDir, "src/components/icon-paths.ts"), file);
console.log(`wrote ${entries.length} icons`);
